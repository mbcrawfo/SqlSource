using System.Text;
using SqlSource.Generation.Models;
using SqlSource.Settings;

namespace SqlSource.Generation.Emitting;

/// <summary>
/// Writes the file of one model: a positional record, or a class with a property for each member, documented.
/// </summary>
internal static class ModelEmitter
{
    private const string Indent = "    ";

    // A model has no member a query names, so it needs none of the pragmas of a type's file.
    private const string Header = "// <auto-generated/>\n#nullable enable\n";

    // A type override can map a database type to a C# type marked [Obsolete], which is what was asked for; the
    // compiler's warning would be in code the consumer cannot change.
    private const string ObsoletePragma = "#pragma warning disable CS0612, CS0618 // A mapped type is obsolete.\n";

    /// <summary>Writes the file of <paramref name="model" />.</summary>
    public static string Emit(Model model)
    {
        var builder = new StringBuilder(Header);
        if (HasObsoleteType(model))
        {
            _ = builder.Append(ObsoletePragma);
        }

        _ = builder.Append('\n');
        var indent = string.Empty;
        if (model.NamespaceText.Length > 0)
        {
            _ = builder.Append("namespace ").Append(model.NamespaceText).Append("\n{\n");
            indent = Indent;
        }

        AppendSummary(builder, indent, model.SummaryXml);
        if (model.Kind is ModelKind.Record or ModelKind.SealedRecord)
        {
            AppendRecord(builder, indent, model);
        }
        else
        {
            AppendClass(builder, indent, model);
        }

        if (indent.Length > 0)
        {
            _ = builder.Append("}\n");
        }

        return builder.ToString();
    }

    // The compiler applies a param of a record to its positional property.
    private static void AppendRecord(StringBuilder builder, string indent, Model model)
    {
        var properties = model.Properties;
        foreach (var property in properties)
        {
            XmlDocWriter.AppendXml(
                builder,
                indent,
                "<param name=\"" + property.Name + "\">" + property.Documentation + "</param>"
            );
        }

        _ = AppendDeclaration(builder, indent, model).Append('(');
        for (var index = 0; index < properties.Count; index++)
        {
            if (index > 0)
            {
                _ = builder.Append(", ");
            }

            _ = AppendType(builder, properties[index]).Append(' ').Append(properties[index].Name);
        }

        _ = builder.Append(");\n");
    }

    // A property of a reference type that is not nullable starts as default!, so that the class compiles under
    // #nullable enable without CS8618 and without a constructor of its own.
    private static void AppendClass(StringBuilder builder, string indent, Model model)
    {
        _ = AppendDeclaration(builder, indent, model).Append('\n').Append(indent).Append("{\n");
        var memberIndent = indent + Indent;
        var properties = model.Properties;
        for (var index = 0; index < properties.Count; index++)
        {
            if (index > 0)
            {
                _ = builder.Append('\n');
            }

            var property = properties[index];
            AppendSummary(builder, memberIndent, property.Documentation);
            _ = AppendType(builder.Append(memberIndent).Append("public "), property)
                .Append(' ')
                .Append(property.Name)
                .Append(" { get; set; }");
            if (!property.IsNullable && !property.Type.IsValueType)
            {
                _ = builder.Append(" = default!;");
            }

            _ = builder.Append('\n');
        }

        _ = builder.Append(indent).Append("}\n");
    }

    private static StringBuilder AppendDeclaration(StringBuilder builder, string indent, Model model) =>
        builder
            .Append(indent)
            .Append(model.IsPublic ? "public " : "internal ")
            .Append(
                model.Kind switch
                {
                    ModelKind.Record => "record ",
                    ModelKind.SealedRecord => "sealed record ",
                    ModelKind.Class => "class ",
                    ModelKind.SealedClass => "sealed class ",
                    _ => "sealed class ",
                }
            )
            .Append(model.Name);

    // T? is Nullable<T> for a value type and the annotation for a reference type: the same text for both.
    private static StringBuilder AppendType(StringBuilder builder, ModelProperty property)
    {
        _ = builder.Append(property.Type.Text);
        return property.IsNullable ? builder.Append('?') : builder;
    }

    private static void AppendSummary(StringBuilder builder, string indent, string summaryXml)
    {
        XmlDocWriter.AppendXml(builder, indent, "<summary>");
        XmlDocWriter.AppendXml(builder, indent, summaryXml);
        XmlDocWriter.AppendXml(builder, indent, "</summary>");
    }

    private static bool HasObsoleteType(Model model)
    {
        foreach (var property in model.Properties)
        {
            if (property.Type.IsObsolete)
            {
                return true;
            }
        }

        return false;
    }
}
