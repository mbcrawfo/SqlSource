namespace SqlSource.Generation;

/// <summary>
/// The attributes that the generator adds to every project that uses it, and the definition of
/// <c>Microsoft.CodeAnalysis.EmbeddedAttribute</c> they are marked with.
/// </summary>
internal static class AttributeSource
{
    public const string HintName = "SqlSourceGenerateAttribute.g.cs";

    public const string EmbeddedHintName = "SqlSource-EmbeddedAttribute.g.cs";

    // Roslyn's own definition, written by the generator instead of AddEmbeddedAttributeDefinition: on Roslyn 4.14 that
    // call writes a file without the header, which analyzers then take for the consumer's code, reporting CA1018 or
    // IDE0161 there.  The declaration is Roslyn's, internal sealed partial, so it merges with the one that another
    // generator's call adds.
    public const string EmbeddedText = """
        // <auto-generated/>

        namespace Microsoft.CodeAnalysis
        {
            internal sealed partial class EmbeddedAttribute : global::System.Attribute
            {
            }
        }

        """;

    public const string AttributeMetadataName = "SqlSource.SqlSourceGenerateAttribute";

    public const string ConverterAttributeMetadataName = "SqlSource.SqlSourceConverterAttribute";

    public const string ConnectionAttributeMetadataName = "SqlSource.SqlSourceConnectionAttribute";

    public const string SourceProperty = "Source";

    public const string GenerateInterfaceProperty = "GenerateInterface";

    public const string InterfaceNameProperty = "InterfaceName";

    public const string DatabaseProperty = "Database";

    // SqlSourceGenerateAttribute is not applied in metadata unless the consumer defines SQLSOURCE_ATTRIBUTES.
    // SqlSourceConverterAttribute is not [Conditional]: a library's converters are found in its metadata by the
    // projects that reference it.  Nor is SqlSourceConnectionAttribute: a repository's connection may be a member of a
    // base class in a referenced assembly.
    //
    // This file goes into every project that references the package, including one that targets a framework older
    // than .NET 8 and so compiles as C# 7.3.  It therefore uses nothing newer: no "#nullable" and no "string?".  Such
    // a project then gets SQLSRC003 if it uses the attribute, not a compiler error in a file it did not write.
    //
    // Every type here is marked [Microsoft.CodeAnalysis.Embedded], whose definition, EmbeddedText, the generator adds
    // beside this file, so that a project that sees the internals of another one that uses SqlSource does not see the
    // other's copies.  A type that is added here is marked too.
    public const string Text = """
        // <auto-generated/>

        namespace SqlSource
        {
            /// <summary>
            /// Marks a static method of one argument as a conversion from its argument's type to its return type, which
            /// the generated query methods call to read a column into a property of the return type or to bind a
            /// parameter of that type from the argument's.  It is not conditional, unlike
            /// <see cref="SqlSourceGenerateAttribute" />: a project that references a library finds the library's
            /// converters in its metadata, so the attribute has to stay there.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.AttributeUsage(global::System.AttributeTargets.Method)]
            internal sealed class SqlSourceConverterAttribute : global::System.Attribute
            {
            }

            /// <summary>
            /// Marks the member, or the primary-constructor parameter, that gives a repository its connection: a
            /// connection string, a <c>DbDataSource</c>, a <c>DbConnection</c> that the repository borrows, or a method
            /// that returns a new <c>DbConnection</c>, or a task of one, and takes nothing or a
            /// <c>CancellationToken</c>.  It is not conditional, unlike <see cref="SqlSourceGenerateAttribute" />: a
            /// repository finds a marked member of a base class in a referenced assembly in its metadata.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.AttributeUsage(
                global::System.AttributeTargets.Field
                    | global::System.AttributeTargets.Property
                    | global::System.AttributeTargets.Method
                    | global::System.AttributeTargets.Parameter,
                AllowMultiple = false,
                Inherited = false
            )]
            internal sealed class SqlSourceConnectionAttribute : global::System.Attribute
            {
                /// <summary>
                /// The database whose queries use the connection, as the <c>database</c> setting names it.  Needed
                /// only when the repository's queries use more than one database.
                /// </summary>
                public string Database { get; set; }
            }

            /// <summary>
            /// Generates code for each query in the <c>.sql</c> files of the type.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.AttributeUsage(
                global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct,
                AllowMultiple = false,
                Inherited = false
            )]
            [global::System.Diagnostics.Conditional("SQLSOURCE_ATTRIBUTES")]
            internal sealed class SqlSourceGenerateAttribute : global::System.Attribute
            {
                /// <summary>
                /// A folder or one <c>.sql</c> file, relative to the folder of the file that carries the attribute:
                /// <c>"."</c> is every <c>.sql</c> file of that folder.  The default is the file named for the type in
                /// that folder, <c>UserRepository.sql</c> for <c>UserRepository</c>.
                /// </summary>
                public string Source { get; set; }

                /// <summary>
                /// Whether a repository gets its interface, which overrides the project's
                /// <c>SqlSourceRepositoryInterfaces</c> when it is written.
                /// </summary>
                public bool GenerateInterface { get; set; }

                /// <summary>
                /// The name of a repository's interface.  The default is the type's name after an <c>I</c>,
                /// <c>IUserRepository</c> for <c>UserRepository</c>.
                /// </summary>
                public string InterfaceName { get; set; }
            }
        }

        """;
}
