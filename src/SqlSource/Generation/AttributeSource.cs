namespace SqlSource.Generation;

/// <summary>
/// The attribute and the enums that the generator adds to every project that uses it, and the definition of
/// <c>Microsoft.CodeAnalysis.EmbeddedAttribute</c> they are marked with.
/// </summary>
internal static class AttributeSource
{
    public const string HintName = "SqlSourceGenerateAttribute.g.cs";

    public const string EmbeddedHintName = "SqlSource-EmbeddedAttribute.g.cs";

    // Roslyn's own definition, written by the generator instead of AddEmbeddedAttributeDefinition: on Roslyn 4.14 that
    // call writes a file without the header, which analyzers then take for the consumer's code, reporting CA1018 or
    // IDE0161 there.  The declaration is Roslyn's, internal sealed partial, so it merges with the one that another
    // generator's call adds.
    public const string EmbeddedText = """
        // <auto-generated/>

        namespace Microsoft.CodeAnalysis
        {
            internal sealed partial class EmbeddedAttribute : global::System.Attribute
            {
            }
        }

        """;

    public const string AttributeMetadataName = "SqlSource.SqlSourceGenerateAttribute";

    public const string LocationMetadataName = "SqlSource.SqlLocation";

    public const string OutputMetadataName = "SqlSource.GeneratorOutput";

    public const string ModelTypeMetadataName = "SqlSource.GeneratorModelType";

    public const string CollectionTypeMetadataName = "SqlSource.GeneratorCollectionType";

    public const string MethodLocationMetadataName = "SqlSource.MethodLocation";

    public const string ConverterAttributeMetadataName = "SqlSource.SqlSourceConverterAttribute";

    public const string SourceProperty = "Source";

    public const string LocationProperty = "SqlLocation";

    public const string ParametersProperty = "Parameters";

    public const string OutputProperty = "Output";

    public const string InputModelSuffixProperty = "InputModelSuffix";

    public const string OutputModelSuffixProperty = "OutputModelSuffix";

    public const string ModelNamespaceProperty = "ModelNamespace";

    public const string InputModelTypeProperty = "InputModelType";

    public const string OutputModelTypeProperty = "OutputModelType";

    public const string MethodLocationProperty = "MethodLocation";

    public const string CollectionTypeProperty = "CollectionType";

    public const string NestedClassProperty = "NestedClass";

    // Only an attribute class can be [Conditional], so the enums stay in the consumer's assembly.  The attribute
    // itself is not applied in metadata unless the consumer defines SQLSOURCE_ATTRIBUTES.  SqlSourceConverterAttribute
    // is not [Conditional]: a library's converters are found in its metadata by the projects that reference it.
    //
    // This file goes into every project that references the package, including one that targets a framework older
    // than .NET 8 and so compiles as C# 7.3.  It therefore uses nothing newer: no "#nullable" and no "string?".  Such
    // a project then gets SQLSRC003 if it uses the attribute, not a compiler error in a file it did not write.
    //
    // Every type here is marked [Microsoft.CodeAnalysis.Embedded], whose definition, EmbeddedText, the generator adds
    // beside this file, so that a project that sees the internals of another one that uses SqlSource does not see the
    // other's copies.  A type that is added here is marked too.
    public const string Text = """
        // <auto-generated/>

        namespace SqlSource
        {
            /// <summary>
            /// Where the members generated for a type marked with <see cref="SqlSourceGenerateAttribute" /> go.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            internal enum SqlLocation
            {
                /// <summary>
                /// In a private static class nested in the type, named by
                /// <see cref="SqlSourceGenerateAttribute.NestedClass" />.
                /// </summary>
                Nested = 0,

                /// <summary>
                /// On the type itself.
                /// </summary>
                Direct = 1,
            }

            /// <summary>
            /// What SqlSource generates for a query.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            internal enum GeneratorOutput
            {
                /// <summary>
                /// The SQL: a constant, or a method when the query has a token.
                /// </summary>
                Sql = 0,

                /// <summary>
                /// The SQL, and a type for the query's parameters and one for its result.
                /// </summary>
                Models = 1,

                /// <summary>
                /// The types, and an asynchronous method that runs the query, which holds its SQL in place of the
                /// constant or the method that <see cref="Sql" /> gives.
                /// </summary>
                CodeGen = 2,
            }

            /// <summary>
            /// The shape of a type that SqlSource generates for a query.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            internal enum GeneratorModelType
            {
                /// <summary>
                /// A positional record.
                /// </summary>
                Record = 0,

                /// <summary>
                /// A sealed positional record.
                /// </summary>
                SealedRecord = 1,

                /// <summary>
                /// A class with a property for each member.
                /// </summary>
                Class = 2,

                /// <summary>
                /// A sealed class with a property for each member.
                /// </summary>
                SealedClass = 3,
            }

            /// <summary>
            /// The type a generated method returns many rows in.  Every one but IAsyncEnumerable is filled before the
            /// method returns.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            internal enum GeneratorCollectionType
            {
                /// <summary>
                /// <c>IEnumerable&lt;T&gt;</c>, over an array.
                /// </summary>
                IEnumerable = 0,

                /// <summary>
                /// <c>ICollection&lt;T&gt;</c>, over a list.
                /// </summary>
                ICollection = 1,

                /// <summary>
                /// <c>IReadOnlyCollection&lt;T&gt;</c>, over an array.
                /// </summary>
                IReadOnlyCollection = 2,

                /// <summary>
                /// <c>IList&lt;T&gt;</c>, over a list.
                /// </summary>
                IList = 3,

                /// <summary>
                /// <c>IReadOnlyList&lt;T&gt;</c>, over an array.
                /// </summary>
                IReadOnlyList = 4,

                /// <summary>
                /// An array.
                /// </summary>
                Array = 5,

                /// <summary>
                /// <c>List&lt;T&gt;</c>.
                /// </summary>
                List = 6,

                /// <summary>
                /// <c>ImmutableArray&lt;T&gt;</c>.
                /// </summary>
                ImmutableArray = 7,

                /// <summary>
                /// <c>ImmutableList&lt;T&gt;</c>.
                /// </summary>
                ImmutableList = 8,

                /// <summary>
                /// <c>IImmutableList&lt;T&gt;</c>, over an immutable list.
                /// </summary>
                IImmutableList = 9,

                /// <summary>
                /// <c>IAsyncEnumerable&lt;T&gt;</c>, each row read as the loop asks for it.
                /// </summary>
                IAsyncEnumerable = 10,
            }

            /// <summary>
            /// Where the methods that run the queries of a type go.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            internal enum MethodLocation
            {
                /// <summary>
                /// In a generated static class beside the type, named after it with <c>Extensions</c>, as extension
                /// methods of <c>DbConnection</c>.
                /// </summary>
                ExtensionClass = 0,

                /// <summary>
                /// On the type, as public static methods.
                /// </summary>
                Public = 1,

                /// <summary>
                /// On the type, as internal static methods.
                /// </summary>
                Internal = 2,

                /// <summary>
                /// On the type, as private static methods.
                /// </summary>
                Private = 3,
            }

            /// <summary>
            /// Marks a static method of one argument as a conversion from its argument's type to its return type, which
            /// the generated query methods call to read a column into a property of the return type or to bind a
            /// parameter of that type from the argument's.  It is not conditional, unlike
            /// <see cref="SqlSourceGenerateAttribute" />: a project that references a library finds the library's
            /// converters in its metadata, so the attribute has to stay there.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.AttributeUsage(global::System.AttributeTargets.Method)]
            internal sealed class SqlSourceConverterAttribute : global::System.Attribute
            {
            }

            /// <summary>
            /// Generates code for each query in the <c>.sql</c> files of the type.
            /// </summary>
            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.AttributeUsage(
                global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct,
                AllowMultiple = false,
                Inherited = false
            )]
            [global::System.Diagnostics.Conditional("SQLSOURCE_ATTRIBUTES")]
            internal sealed class SqlSourceGenerateAttribute : global::System.Attribute
            {
                /// <summary>
                /// A folder or one <c>.sql</c> file, relative to the folder of the file that carries the attribute:
                /// <c>"."</c> is every <c>.sql</c> file of that folder.  The default is the file named for the type in
                /// that folder, <c>UserRepository.sql</c> for <c>UserRepository</c>.
                /// </summary>
                public string Source { get; set; }

                /// <summary>
                /// Where the generated members go.  The default is
                /// <see cref="global::SqlSource.SqlLocation.Nested" />.
                /// </summary>
                public SqlLocation SqlLocation { get; set; }

                /// <summary>
                /// The name of the class that holds the generated members under
                /// <see cref="global::SqlSource.SqlLocation.Nested" />.  The default is the <c>nestedClass</c> of the
                /// settings files of the folder of this type's file, else <c>Sql</c>.
                /// </summary>
                public string NestedClass { get; set; }

                /// <summary>
                /// What is generated for the queries of the type's files.  The default is the <c>output</c> of the
                /// settings files of the folder of the <c>.sql</c> file, else
                /// <see cref="global::SqlSource.GeneratorOutput.CodeGen" />.  A marker in a file comes first.
                /// </summary>
                public GeneratorOutput Output { get; set; }

                /// <summary>
                /// What ends the name of the type of a query's parameters.  The default is the
                /// <c>inputModelSuffix</c> of the settings files of the folder of the <c>.sql</c> file, else
                /// <c>Params</c>.  A marker in a file comes first.
                /// </summary>
                public string InputModelSuffix { get; set; }

                /// <summary>
                /// What ends the name of the type of a row of a query's result.  The default is the
                /// <c>outputModelSuffix</c> of the settings files of the folder of the <c>.sql</c> file, else
                /// <c>Dto</c>.  A marker in a file comes first.
                /// </summary>
                public string OutputModelSuffix { get; set; }

                /// <summary>
                /// The namespace of the types generated for the queries.  The default is the <c>modelNamespace</c>
                /// of the settings files of the folder of the <c>.sql</c> file, else the namespace of this type.  A
                /// marker in a file comes first.
                /// </summary>
                public string ModelNamespace { get; set; }

                /// <summary>
                /// The shape of the type of a query's parameters.  The default is the <c>inputModelType</c> of the
                /// settings files of the folder of the <c>.sql</c> file, else
                /// <see cref="global::SqlSource.GeneratorModelType.SealedRecord" />.  A marker in a file comes first.
                /// </summary>
                public GeneratorModelType InputModelType { get; set; }

                /// <summary>
                /// The shape of the type of a row of a query's result.  The default is the <c>outputModelType</c> of
                /// the settings files of the folder of the <c>.sql</c> file, else
                /// <see cref="global::SqlSource.GeneratorModelType.SealedRecord" />.  A marker in a file comes first.
                /// </summary>
                public GeneratorModelType OutputModelType { get; set; }

                /// <summary>
                /// Where the methods that run the queries go.  The default is
                /// <see cref="global::SqlSource.MethodLocation.ExtensionClass" />.
                /// </summary>
                public MethodLocation MethodLocation { get; set; }

                /// <summary>
                /// The type a method returns many rows in.  The default is the <c>collectionType</c> of the settings
                /// files of the folder of the <c>.sql</c> file, else
                /// <see cref="global::SqlSource.GeneratorCollectionType.Array" />.  A marker in a file comes first.
                /// </summary>
                public GeneratorCollectionType CollectionType { get; set; }

                /// <summary>
                /// Generator parameters for the queries of the type's files, separated by spaces, as a
                /// <c>-- generator:</c> line holds them.  The default is the <c>generatorParameters</c> of the
                /// settings files of the folder of the <c>.sql</c> file, else none.  A line in a file comes first.
                /// </summary>
                public string Parameters { get; set; }
            }
        }

        """;
}
