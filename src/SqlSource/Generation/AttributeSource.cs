using System.Collections.Immutable;

namespace SqlSource.Generation;

/// <summary>
/// The attribute and the enums that the generator adds to every project that uses it.
/// </summary>
internal static class AttributeSource
{
    public const string HintName = "SqlSourceGenerateAttribute.g.cs";

    public const string AttributeMetadataName = "SqlSource.SqlSourceGenerateAttribute";

    public const string LocationMetadataName = "SqlSource.SqlLocation";

    public const string OutputMetadataName = "SqlSource.GeneratorOutput";

    public const string ModelTypeMetadataName = "SqlSource.GeneratorModelType";

    public const string CollectionTypeMetadataName = "SqlSource.GeneratorCollectionType";

    public const string MethodLocationMetadataName = "SqlSource.MethodLocation";

    public const string UnexpectedRowCountMetadataName = "SqlSource.UnexpectedRowCountException";

    public const string PathProperty = "Path";

    public const string LocationProperty = "SqlLocation";

    public const string ParametersProperty = "Parameters";

    public const string OutputProperty = "Output";

    public const string InputModelSuffixProperty = "InputModelSuffix";

    public const string OutputModelSuffixProperty = "OutputModelSuffix";

    public const string ModelNamespaceProperty = "ModelNamespace";

    public const string InputModelTypeProperty = "InputModelType";

    public const string OutputModelTypeProperty = "OutputModelType";

    public const string MethodLocationProperty = "MethodLocation";

    public const string CollectionTypeProperty = "CollectionType";

    public const string NestedClassProperty = "NestedClass";

    /// <summary>
    /// The metadata name of every type that <see cref="Text" /> declares.  A project that sees the internals of
    /// another one that uses SqlSource sees each of them twice, and <c>AttributeConflictSuppressor</c> turns the
    /// compiler's warning off for exactly these.
    /// </summary>
    public static ImmutableArray<string> GeneratedTypes { get; } =
        ImmutableArray.Create(
            AttributeMetadataName,
            LocationMetadataName,
            OutputMetadataName,
            ModelTypeMetadataName,
            CollectionTypeMetadataName,
            MethodLocationMetadataName,
            UnexpectedRowCountMetadataName
        );

    // Only an attribute class can be [Conditional], so the enums stay in the consumer's assembly.  The attribute
    // itself is not applied in metadata unless the consumer defines SQLSOURCE_ATTRIBUTES.
    //
    // This file goes into every project that references the package, including one that targets a framework older
    // than .NET 8 and so compiles as C# 7.3.  It therefore uses nothing newer: no "#nullable" and no "string?".  Such
    // a project then gets SQLSRC003 if it uses the attribute, not a compiler error in a file it did not write.
    //
    // A project that sees the internals of another one that uses SqlSource gets CS0436 at each use of these types.
    // The pragma below covers the uses in this file, and Diagnostics/AttributeConflictSuppressor.cs the uses in the
    // project's own code.  A type that is added here is added to GeneratedTypes.
    public const string Text = """
        // <auto-generated/>
        // A project that can see the internals of another one that uses SqlSource sees these types twice.
        #pragma warning disable CS0436

        namespace SqlSource
        {
            /// <summary>
            /// Where the members generated for a type marked with <see cref="SqlSourceGenerateAttribute" /> go.
            /// </summary>
            internal enum SqlLocation
            {
                /// <summary>
                /// In a private static class nested in the type, named by
                /// <see cref="SqlSourceGenerateAttribute.NestedClass" />.
                /// </summary>
                Nested = 0,

                /// <summary>
                /// On the type itself.
                /// </summary>
                Direct = 1,
            }

            /// <summary>
            /// What SqlSource generates for a query.
            /// </summary>
            internal enum GeneratorOutput
            {
                /// <summary>
                /// The SQL: a constant, or a method when the query has a token.
                /// </summary>
                Sql = 0,

                /// <summary>
                /// The SQL, and a type for the query's parameters and one for its result.
                /// </summary>
                Models = 1,

                /// <summary>
                /// The SQL, the types, and, in a later release, a method that runs the query.  Until then it generates
                /// what <see cref="Models" /> does.
                /// </summary>
                CodeGen = 2,
            }

            /// <summary>
            /// The shape of a type that SqlSource generates for a query.
            /// </summary>
            internal enum GeneratorModelType
            {
                /// <summary>
                /// A positional record.
                /// </summary>
                Record = 0,

                /// <summary>
                /// A sealed positional record.
                /// </summary>
                SealedRecord = 1,

                /// <summary>
                /// A class with a property for each member.
                /// </summary>
                Class = 2,

                /// <summary>
                /// A sealed class with a property for each member.
                /// </summary>
                SealedClass = 3,
            }

            /// <summary>
            /// The type a generated method returns many rows in.  Every one is filled before the method returns.  It
            /// has no effect until the methods that run the queries arrive in a later release.
            /// </summary>
            internal enum GeneratorCollectionType
            {
                /// <summary>
                /// <c>IEnumerable&lt;T&gt;</c>, over an array.
                /// </summary>
                IEnumerable = 0,

                /// <summary>
                /// <c>ICollection&lt;T&gt;</c>, over a list.
                /// </summary>
                ICollection = 1,

                /// <summary>
                /// <c>IReadOnlyCollection&lt;T&gt;</c>, over an array.
                /// </summary>
                IReadOnlyCollection = 2,

                /// <summary>
                /// <c>IList&lt;T&gt;</c>, over a list.
                /// </summary>
                IList = 3,

                /// <summary>
                /// <c>IReadOnlyList&lt;T&gt;</c>, over an array.
                /// </summary>
                IReadOnlyList = 4,

                /// <summary>
                /// An array.
                /// </summary>
                Array = 5,

                /// <summary>
                /// <c>List&lt;T&gt;</c>.
                /// </summary>
                List = 6,

                /// <summary>
                /// <c>ImmutableArray&lt;T&gt;</c>.
                /// </summary>
                ImmutableArray = 7,

                /// <summary>
                /// <c>ImmutableList&lt;T&gt;</c>.
                /// </summary>
                ImmutableList = 8,

                /// <summary>
                /// <c>IImmutableList&lt;T&gt;</c>, over an immutable list.
                /// </summary>
                IImmutableList = 9,
            }

            /// <summary>
            /// Where the methods that run the queries of a type go.  It has no effect until those methods arrive in a
            /// later release.
            /// </summary>
            internal enum MethodLocation
            {
                /// <summary>
                /// In a generated static class beside the type, as extension methods of <c>DbConnection</c>.
                /// </summary>
                ExtensionClass = 0,

                /// <summary>
                /// On the type, as public static methods.
                /// </summary>
                Public = 1,

                /// <summary>
                /// On the type, as internal static methods.
                /// </summary>
                Internal = 2,

                /// <summary>
                /// On the type, as private static methods.
                /// </summary>
                Private = 3,
            }

            /// <summary>
            /// What a generated method throws when a query that must return one row returns none, or more than one.  It
            /// derives from <see cref="global::System.InvalidOperationException" />, so a caller in another assembly
            /// that does not know this type catches that.
            /// </summary>
            internal sealed class UnexpectedRowCountException : global::System.InvalidOperationException
            {
                /// <summary>
                /// Creates the exception for a query.
                /// </summary>
                /// <param name="queryName">The name of the query.</param>
                /// <param name="moreThanOne">
                /// <c>true</c> if the query returned more than one row, <c>false</c> if it returned none.
                /// </param>
                public UnexpectedRowCountException(string queryName, bool moreThanOne)
                    : base(
                        "The query '" + queryName + "' returned " + (moreThanOne ? "more than one row." : "no rows.")
                    )
                {
                    QueryName = queryName;
                }

                /// <summary>
                /// The name of the query.
                /// </summary>
                public string QueryName { get; }
            }

            /// <summary>
            /// Generates code for each query in the <c>.sql</c> files of the type.
            /// </summary>
            [global::System.AttributeUsage(
                global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct,
                AllowMultiple = false,
                Inherited = false
            )]
            [global::System.Diagnostics.Conditional("SQLSOURCE_ATTRIBUTES")]
            internal sealed class SqlSourceGenerateAttribute : global::System.Attribute
            {
                /// <summary>
                /// A folder or one <c>.sql</c> file, relative to the folder of the file that carries the attribute.
                /// The default is that folder.
                /// </summary>
                public string Path { get; set; }

                /// <summary>
                /// Where the generated members go.  The default is
                /// <see cref="global::SqlSource.SqlLocation.Nested" />.
                /// </summary>
                public SqlLocation SqlLocation { get; set; }

                /// <summary>
                /// The name of the class that holds the generated members under
                /// <see cref="global::SqlSource.SqlLocation.Nested" />.  The default is the project's
                /// <c>SqlSourceNestedClass</c>, else <c>Sql</c>.
                /// </summary>
                public string NestedClass { get; set; }

                /// <summary>
                /// What is generated for the queries of the type's files.  The default is
                /// <see cref="global::SqlSource.GeneratorOutput.CodeGen" />.  A marker in a file comes first.
                /// </summary>
                public GeneratorOutput Output { get; set; }

                /// <summary>
                /// What ends the name of the type of a query's parameters.  The default is <c>Params</c>.
                /// </summary>
                public string InputModelSuffix { get; set; }

                /// <summary>
                /// What ends the name of the type of a row of a query's result.  The default is <c>Dto</c>.
                /// </summary>
                public string OutputModelSuffix { get; set; }

                /// <summary>
                /// The namespace of the types generated for the queries.  The default is the namespace of this
                /// type.
                /// </summary>
                public string ModelNamespace { get; set; }

                /// <summary>
                /// The shape of the type of a query's parameters.  The default is
                /// <see cref="global::SqlSource.GeneratorModelType.SealedRecord" />.
                /// </summary>
                public GeneratorModelType InputModelType { get; set; }

                /// <summary>
                /// The shape of the type of a row of a query's result.  The default is
                /// <see cref="global::SqlSource.GeneratorModelType.SealedRecord" />.
                /// </summary>
                public GeneratorModelType OutputModelType { get; set; }

                /// <summary>
                /// Where the methods that run the queries go.  The default is
                /// <see cref="global::SqlSource.MethodLocation.ExtensionClass" />.  It has no effect until those
                /// methods arrive in a later release.
                /// </summary>
                public MethodLocation MethodLocation { get; set; }

                /// <summary>
                /// The type a method returns many rows in.  The default is
                /// <see cref="global::SqlSource.GeneratorCollectionType.Array" />.  It has no effect until the methods
                /// that run the queries arrive in a later release.
                /// </summary>
                public GeneratorCollectionType CollectionType { get; set; }

                /// <summary>
                /// Generator parameters for the queries of the type's files, separated by spaces, as a
                /// <c>-- generator:</c> line holds them.  A line in a file comes first.
                /// </summary>
                public string Parameters { get; set; }
            }
        }

        """;
}
