namespace SqlSource.Generation.Exceptions;

/// <summary>
/// The exceptions that a generated query method throws, which the generator writes into a project unless a referenced
/// assembly that the project sees gives it all three: see <see cref="ExceptionProbe" />.
/// </summary>
internal static class ExceptionSource
{
    public const string HintName = "SqlSource-Exceptions.g.cs";

    public const string UnexpectedRowCountMetadataName = "SqlSource.UnexpectedRowCountException";

    public const string TransactionRolledBackMetadataName = "SqlSource.TransactionRolledBackException";

    public const string CollectionItemMetadataName = "SqlSource.CollectionItemException";

    // Where the text has the classes' accessibility.
    private const string Accessibility = "$accessibility$";

    // This file goes into every project that references the package, as the attribute's does, including one that
    // targets a framework older than .NET 8 and so compiles as C# 7.3.  It therefore uses nothing newer: no "#nullable"
    // and no "string?".  CollectionItemException overrides members that DbException has from .NET 6 and that older
    // frameworks, netstandard2.1 among them, lack, and this file is compiled into every project that references the
    // package, so those members are under NET6_0_OR_GREATER.  A project that uses the methods targets .NET 8 or
    // later (README.md, "Supported environments"), and a copy that it would reuse from a project compiled without the
    // symbol is SQLSRC038 (ExceptionProbe).
    private const string Template = """
        // <auto-generated/>
        namespace SqlSource
        {
            /// <summary>
            /// What a generated method throws when a query that must return one row returns none, or more than one.  It
            /// derives from <see cref="global::System.InvalidOperationException" />, so a caller in another assembly
            /// that does not know this type catches that.
            /// </summary>
            $accessibility$ sealed class UnexpectedRowCountException : global::System.InvalidOperationException
            {
                /// <summary>
                /// Creates the exception for a query.
                /// </summary>
                /// <param name="queryName">The name of the query.</param>
                /// <param name="moreThanOne">
                /// <c>true</c> if the query returned more than one row, <c>false</c> if it returned none.
                /// </param>
                public UnexpectedRowCountException(string queryName, bool moreThanOne)
                    : base(
                        "The query '" + queryName + "' returned " + (moreThanOne ? "more than one row." : "no rows.")
                    )
                {
                    QueryName = queryName;
                }

                /// <summary>
                /// Creates the exception for a query that ran over a collection, at one of its items.
                /// </summary>
                /// <param name="queryName">The name of the query.</param>
                /// <param name="moreThanOne">
                /// <c>true</c> if the query returned more than one row for the item, <c>false</c> if it returned none.
                /// </param>
                /// <param name="itemIndex">The item's position in the collection, counted from 0.</param>
                public UnexpectedRowCountException(string queryName, bool moreThanOne, int itemIndex)
                    : base(
                        "The query '"
                            + queryName
                            + "' returned "
                            + (moreThanOne ? "more than one row" : "no rows")
                            + " for item "
                            + itemIndex.ToString(global::System.Globalization.CultureInfo.InvariantCulture)
                            + "."
                    )
                {
                    QueryName = queryName;
                    ItemIndex = itemIndex;
                }

                /// <summary>
                /// The name of the query.
                /// </summary>
                public string QueryName { get; }

                /// <summary>
                /// The position of the item that the query returned the wrong number of rows for, counted from 0, or
                /// <c>null</c> when the query did not run over a collection.
                /// </summary>
                public int? ItemIndex { get; }
            }

            /// <summary>
            /// What a generated SQL Server method throws when it was given a transaction, threw an exception of its
            /// own, and an error that the rest of its query raised then rolled the transaction back.  Its inner
            /// exception is the method's own.  It derives from <see cref="global::System.InvalidOperationException" />,
            /// so a caller in another assembly that does not know this type catches that.
            /// </summary>
            $accessibility$ sealed class TransactionRolledBackException : global::System.InvalidOperationException
            {
                /// <summary>
                /// Creates the exception for a query.
                /// </summary>
                /// <param name="queryName">The name of the query.</param>
                /// <param name="innerException">The exception that the method threw.</param>
                public TransactionRolledBackException(string queryName, global::System.Exception innerException)
                    : base(
                        "The transaction was rolled back by an error that the query '"
                            + queryName
                            + "' raised after the inner exception was thrown.",
                        innerException
                    )
                {
                    QueryName = queryName;
                }

                /// <summary>
                /// The name of the query.
                /// </summary>
                public string QueryName { get; }
            }

            /// <summary>
            /// What a generated method that runs a query over a collection throws when the database reports an error at
            /// one of its items.  Its inner exception is the driver's own, and it passes on what
            /// <see cref="global::System.Data.Common.DbException" /> lets it, so a caller that catches that, or tests
            /// <c>IsTransient</c>, sees the same.
            /// </summary>
            $accessibility$ sealed class CollectionItemException : global::System.Data.Common.DbException
            {
        #if NET6_0_OR_GREATER
                private readonly string _sqlState;

                private readonly bool _isTransient;

                private readonly global::System.Data.Common.DbBatchCommand _batchCommand;
        #endif

                /// <summary>
                /// Creates the exception for a query.
                /// </summary>
                /// <param name="queryName">The name of the query.</param>
                /// <param name="itemIndex">The item's position in the collection, counted from 0.</param>
                /// <param name="inner">The exception that the driver threw.</param>
                public CollectionItemException(
                    string queryName,
                    int itemIndex,
                    global::System.Data.Common.DbException inner
                )
                    : base(
                        "The query '"
                            + queryName
                            + "' failed at item "
                            + itemIndex.ToString(global::System.Globalization.CultureInfo.InvariantCulture)
                            + ": "
                            + inner.Message,
                        inner
                    )
                {
                    QueryName = queryName;
                    ItemIndex = itemIndex;
        #if NET6_0_OR_GREATER
                    _sqlState = inner.SqlState;
                    _isTransient = inner.IsTransient;
                    _batchCommand = inner.BatchCommand;
        #endif
                    HResult = inner.HResult;
                }

                /// <summary>
                /// The name of the query.
                /// </summary>
                public string QueryName { get; }

                /// <summary>
                /// The position of the item that the database reported the error at, counted from 0.
                /// </summary>
                public int ItemIndex { get; }

        #if NET6_0_OR_GREATER
                /// <summary>
                /// The inner exception's <c>SqlState</c>.
                /// </summary>
                public override string SqlState => _sqlState;

                /// <summary>
                /// The inner exception's <c>IsTransient</c>.
                /// </summary>
                public override bool IsTransient => _isTransient;

                /// <summary>
                /// The inner exception's batch command.
                /// </summary>
                protected override global::System.Data.Common.DbBatchCommand DbBatchCommand => _batchCommand;
        #endif
            }
        }

        """;

    private static readonly string InternalText = Template.Replace(Accessibility, "internal");

    private static readonly string PublicText = Template.Replace(Accessibility, "public");

    /// <summary>
    /// The text of the file, with its classes <c>public</c> when <paramref name="isPublic" /> is set, as
    /// <see cref="PublicExceptions" /> reads it, and <c>internal</c> otherwise.
    /// </summary>
    public static string TextFor(bool isPublic) => isPublic ? PublicText : InternalText;
}
