-- The schema every fixture case of the PostgreSQL describer is recorded against, and every container test of
-- tests/DatabaseTests/Postgres runs against.  A change to it can move the OIDs of its types, which the captures
-- hold: record every case again with tools/record-fixtures.sh postgres.

CREATE SCHEMA billing;

CREATE DOMAIN email_t AS varchar(254) CHECK (VALUE LIKE '%@%');

CREATE DOMAIN money_t AS numeric(10, 2);

CREATE TYPE user_status AS ENUM ('active', 'disabled');

-- A base type outside pg_catalog with a modifier of its own, as an extension's type has: varchar's functions under
-- another name, so that the server spells tagged(7) by varchar's typmodout.
CREATE TYPE tagged;
CREATE FUNCTION tagged_in(cstring, oid, integer) RETURNS tagged AS 'varcharin' LANGUAGE internal IMMUTABLE STRICT;
CREATE FUNCTION tagged_out(tagged) RETURNS cstring AS 'varcharout' LANGUAGE internal IMMUTABLE STRICT;
CREATE TYPE tagged (
    INPUT = tagged_in,
    OUTPUT = tagged_out,
    TYPMOD_IN = varchartypmodin,
    TYPMOD_OUT = varchartypmodout,
    LIKE = varchar
);

CREATE TABLE users (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    email email_t,
    status user_status NOT NULL DEFAULT 'active',
    tags text[] NOT NULL DEFAULT '{}',
    balance numeric(18, 2) NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    name_upper text GENERATED ALWAYS AS (upper(name)) STORED
);

CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users (id),
    total numeric(18, 2) NOT NULL,
    placed_at timestamptz NOT NULL DEFAULT now(),
    note text
);

CREATE TABLE bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users (id),
    during tstzrange NOT NULL,
    slots int4multirange,
    tags text[] NOT NULL DEFAULT '{}'
);

-- One column for each base type the describer's tests name.
CREATE TABLE samples (
    id integer PRIMARY KEY,
    flag boolean NOT NULL,
    small smallint,
    big bigint,
    ratio real,
    amount double precision,
    code char(2),
    label text,
    born date,
    at_time time,
    at_local timestamp(3),
    span interval,
    token uuid,
    payload bytea,
    document jsonb
);

-- One column for each modifier that only the server's spelling holds: the fields of an interval, the modifier of an
-- array's element and the modifier of a type outside pg_catalog; and a domain whose base has more than a length.
CREATE TABLE modifiers (
    ym interval year to month,
    ds interval day to second(3),
    names varchar(10)[],
    tag tagged(7),
    tags tagged(7)[],
    amount money_t
);

CREATE TABLE billing.invoices (
    id integer PRIMARY KEY,
    order_id bigint NOT NULL,
    amount numeric(18, 2) NOT NULL,
    issued_on date NOT NULL
);

CREATE VIEW active_users AS
SELECT id, name, email, status
FROM users
WHERE deleted_at IS NULL;

CREATE VIEW user_orders AS
SELECT u.id AS user_id, u.name, o.id AS order_id, o.total
FROM users AS u
LEFT JOIN orders AS o ON o.user_id = u.id;
