    [Fact]
    public void Run_NestedMode_PutsTheConstantsInAPrivateSqlClass()
    {
        var run = GeneratorHarness.Run(
            """
            using SqlSource;

            namespace App;

            [SqlQueries]
            public partial class Sample
            {
                public static string First => Sql.GetUser;

                public static string Second => Sql.ListUsers;
            }
            """,
            new SqlFile(
                "/app/Repo/Users.sql",
                """
                -- Queries for users.
                -- name: GetUser
                -- summary: Loads one user by id.
                SELECT id, name -- the columns
                FROM users
                WHERE id = @id;

                -- name: ListUsers
                SELECT id, name FROM users;
                """
            )
        );

        run.Diagnostics.ShouldBeEmpty();
        run.CompilationErrors.ShouldBeEmpty();
        run.GeneratedCodeWarnings.ShouldBeEmpty();
        run.Sources.Keys.ShouldBe(["SqlQueriesAttribute.g.cs", "App.Sample.g.cs"], ignoreOrder: true);
        run.Sources["App.Sample.g.cs"]
            .ShouldBe(
                """
                // <auto-generated/>
                #nullable enable
                #pragma warning disable CS0108 // A query can have the name of an inherited member.

                namespace App
                {
                    partial class Sample
                    {
                        private static class Sql
                        {
                            /// <summary>
                            /// Loads one user by id.
                            /// </summary>
                            /// <remarks>
                            /// <code>
                            /// SELECT id, name
                            /// FROM users
                            /// WHERE id = @id;
                            /// </code>
                            /// </remarks>
                            public const string GetUser = "SELECT id, name\nFROM users\nWHERE id = @id;";

                            /// <summary>
                            /// The <c>ListUsers</c> query from <c>Users.sql</c>.
                            /// </summary>
                            /// <remarks>
                            /// <code>
                            /// SELECT id, name FROM users;
                            /// </code>
                            /// </remarks>
                            public const string ListUsers = "SELECT id, name FROM users;";
                        }
                    }
                }

                """
            );
    }

