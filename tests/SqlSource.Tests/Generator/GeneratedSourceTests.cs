    [Fact]
    public void Run_QueryWithTokens_IsAMethodBesideTheConstantsOfItsFile()
    {
        var run = GeneratorHarness.Run(
            """
            using SqlSource;

            namespace App;

            [SqlQueries(Mode = SqlQueriesMode.Direct)]
            public partial class Sample
            {
