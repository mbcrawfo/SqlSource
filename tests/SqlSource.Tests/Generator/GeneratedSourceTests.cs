            .ShouldBe(
                """
                // <auto-generated/>
                #nullable enable
                #pragma warning disable CS0108, CS0114 // A query can have the name of an inherited member.

                namespace App
                {
                    partial class Sample
                    {
                        private static class Sql
                        {
                            /// <summary>
                            /// Loads one user by id.
                            /// </summary>
                            /// <remarks>
                            /// <code>
                            /// SELECT id, name
                            /// FROM users
                            /// WHERE id = @id;
                            /// </code>
                            /// </remarks>
                            public const string GetUser = "SELECT id, name\nFROM users\nWHERE id = @id;";

                            /// <summary>
                            /// The <c>ListUsers</c> query from <c>Users.sql</c>.
                            /// </summary>
