using Shouldly;
using SqlSource.Parsing;
using SqlSource.Snapshot;
using SqlSource.Testing.Generator;
using SqlSource.Testing.Snapshot;
using Xunit;
using OutputKind = SqlSource.Settings.OutputKind;

namespace SqlSource.Tests.Generator;

// The models of an mssql file with a current sidecar: a run at Models under mssql on SqlClient 7, where the file is
// checked against its sidecar, its columns are typed by the map of SQL Server, and a table of dbo is named without its
// schema.  Every model must compile without a warning.
public sealed class SqlServerModelTests
{
    // The database and the version of the server that the entry says it was described against.
    private const string Database = "main";

    private const string ServerVersion = "17.0";

    private static readonly SqlFile Orders = new(
        GeneratorHarness.UsersPath,
        "-- name: GetOrder\nSELECT id, note, placed_at, paid FROM dbo.orders WHERE id = @id;\n"
    );

    [Fact]
    public void Run_ColumnsOfDboOrders_AreTheModelOrdersDtoWithTheTypesOfSqlServer()
    {
        var run = Run(Orders, "dbo", "orders");

        run.Diagnostics.ShouldBeEmpty();
        run.CompilationErrors.ShouldBeEmpty();
        run.GeneratedCodeWarnings.ShouldBeEmpty();
        run.Sources.Keys.ShouldContain("App.OrdersDto-Model.g.cs");
        run.Sources.Keys.ShouldNotContain("App.DboOrdersDto-Model.g.cs");
        run.Sources["App.OrdersDto-Model.g.cs"]
            .ShouldBe(
                """
                // <auto-generated/>
                #nullable enable

                namespace App
                {
                    /// <summary>
                    /// A row of the table <c>dbo.orders</c>, read by the query <c>GetOrder</c> from <c>Users.sql</c>.
                    /// </summary>
                    /// <param name="Id">The column <c>id</c>, <c>int</c>.</param>
                    /// <param name="Note">The column <c>note</c>, <c>nvarchar</c>.</param>
                    /// <param name="PlacedAt">The column <c>placed_at</c>, <c>datetime2</c>.</param>
                    /// <param name="Paid">The column <c>paid</c>, <c>bit</c>.</param>
                    public sealed record OrdersDto(int Id, string Note, global::System.DateTime PlacedAt, bool Paid);
                }

                """
            );
    }

    // The schema is dropped for dbo alone on SQL Server: public is a schema like any other there.
    [Theory]
    [InlineData("public", "orders", "App.PublicOrdersDto-Model.g.cs")]
    [InlineData("billing", "orders", "App.BillingOrdersDto-Model.g.cs")]
    [InlineData("DBO", "orders", "App.DBOOrdersDto-Model.g.cs")]
    public void Run_TableOfAnotherSchema_HasTheSchemaBeforeItsName(string schema, string table, string expected)
    {
        var run = Run(Orders, schema, table);

        run.Diagnostics.ShouldBeEmpty();
        run.CompilationErrors.ShouldBeEmpty();
        run.GeneratedCodeWarnings.ShouldBeEmpty();
        run.Sources.Keys.ShouldContain(expected);
    }

    private static GeneratorRun Run(SqlFile file, string schema, string table)
    {
        var entry = TestSidecars.Entry(
            "GetOrder",
            Sidecars.HashOf(file, "GetOrder", SqlDialect.SqlServer),
            "mssql",
            Database,
            ServerVersion,
            matchesTable: new SidecarTable(schema, table),
            parameters: [TestSidecars.Parameter(0, "id", TestSidecars.SqlServer("int"), false)],
            columns:
            [
                TestSidecars.Column(0, "id", TestSidecars.SqlServer("int")),
                TestSidecars.Column(1, "note", TestSidecars.SqlServer("nvarchar", 100)),
                TestSidecars.Column(2, "placed_at", TestSidecars.SqlServer("datetime2", 8)),
                TestSidecars.Column(3, "paid", TestSidecars.SqlServer("bit", 1)),
            ]
        );

        return GeneratorHarness.Run(
            OutputKind.Models,
            [new SourceFile(GeneratorHarness.SourcePath, ModelRuns.Source)],
            [file, Sidecars.Of(file, entry)],
            references: [SqlClientReferences.SqlClient7],
            dialect: "mssql"
        );
    }
}
