using System.Collections.Generic;
using Shouldly;
using SqlSource.Testing.Generator;
using Xunit;
using static SqlSource.Testing.Generator.ModelRuns;

namespace SqlSource.Tests.Generator;

// The warnings a model gives for the obsolete and experimental types it names: the pragma that disables their ids, in
// the order the generator writes it, and the type that no pragma can make usable.  Each run is at Models under
// postgres on Npgsql 10, as the runs of ModelTests are.
public sealed class ModelWarningTests
{
    private const string UsersPath = "/app/Repo/Users.sql";

    private static readonly SqlFile Users = new(
        UsersPath,
        "-- name: GetUser\nSELECT id, name FROM users WHERE id = @id;\n"
    );

    // The pragma, the order and = default! where it is needed, in a class in the global namespace.
    [Fact]
    public void Run_GlobalClassSortedWithAnObsoleteType_CompilesWithoutAWarning()
    {
        var source = """
            using SqlSource;

            [SqlSourceGenerate]
            public partial class Sample;

            namespace MyApp
            {
                [System.Obsolete]
                public struct OldId;

                [System.Obsolete("Use another.")]
                public sealed class OldName;
            }
            """;

        var run = Run(
            source,
            [
                Users,
                Sidecars.Of(
                    Users,
                    Entry(
                        Users,
                        "GetUser",
                        [],
                        [Column("note", Text, nullable: true), Column("name", Text), Column("id"), Column("tag", Text)]
                    )
                ),
            ],
            new Dictionary<string, string?>
            {
                ["SqlSourceOutputModelType"] = "class",
                ["SqlSourceGeneratorParameters"] = "sort-output",
                ["SqlSourceTypeOverrides"] = "int4=MyApp.OldId text=MyApp.OldName",
            }
        );

        AssertClean(run);
        run.Sources["GetUserDto-Model.g.cs"]
            .ShouldBe(
                """
                // <auto-generated/>
                #nullable enable
                #pragma warning disable CS0612, CS0618 // A mapped type is obsolete or experimental.

                /// <summary>
                /// A row of the query <c>GetUser</c> from <c>Users.sql</c>.
                /// </summary>
                public class GetUserDto
                {
                    /// <summary>
                    /// The column <c>id</c>, <c>integer</c>.
                    /// </summary>
                    public global::MyApp.OldId Id { get; set; }

                    /// <summary>
                    /// The column <c>name</c>, <c>text</c>.
                    /// </summary>
                    public global::MyApp.OldName Name { get; set; } = default!;

                    /// <summary>
                    /// The column <c>note</c>, <c>text</c>.
                    /// </summary>
                    public global::MyApp.OldName? Note { get; set; }

                    /// <summary>
                    /// The column <c>tag</c>, <c>text</c>.
                    /// </summary>
                    public global::MyApp.OldName Tag { get; set; } = default!;
                }

                """
            );
    }

    // An [Obsolete] with a DiagnosticId is reported under that id, not CS0612 or CS0618.
    [Fact]
    public void Run_ObsoleteTypeWithADiagnosticId_DisablesThatId()
    {
        var source =
            Source
            + """

                namespace MyApp
                {
                    [System.Obsolete("Use another.", DiagnosticId = "MYAPP001")]
                    public sealed class OldName;
                }
                """;

        var run = Run(
            source,
            [Users, Sidecars.Of(Users, Entry(Users, "GetUser", [], [Column("name", Text)]))],
            new Dictionary<string, string?> { ["SqlSourceTypeOverrides"] = "text=MyApp.OldName" }
        );

        AssertClean(run);
        run.Sources["App.GetUserDto-Model.g.cs"]
            .ShouldStartWith(
                "// <auto-generated/>\n#nullable enable\n"
                    + "#pragma warning disable MYAPP001 // A mapped type is obsolete or experimental.\n\n"
            );
    }

    // An [Experimental] type is an error under its id unless the id is disabled.  The ids of a model are written once
    // each, in ordinal order, whatever the order of its properties.
    [Fact]
    public void Run_ExperimentalTypeBesideAnObsoleteOne_DisablesEachIdOnceInOrder()
    {
        var source =
            Source
            + """

                namespace MyApp
                {
                    [System.Diagnostics.CodeAnalysis.Experimental("TRIAL001")]
                    public readonly struct TrialId;

                    [System.Obsolete]
                    public sealed class OldName;
                }
                """;

        var run = Run(
            source,
            [
                Users,
                Sidecars.Of(
                    Users,
                    Entry(Users, "GetUser", [], [Column("id"), Column("name", Text), Column("note", Text)])
                ),
            ],
            new Dictionary<string, string?> { ["SqlSourceTypeOverrides"] = "int4=MyApp.TrialId text=MyApp.OldName" }
        );

        AssertClean(run);
        run.Sources["App.GetUserDto-Model.g.cs"]
            .ShouldStartWith(
                "// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0612, CS0618, TRIAL001 "
                    + "// A mapped type is obsolete or experimental.\n\n"
            );
    }

    // A pragma takes a keyword as an id, so a type whose id is one is disabled like any other.
    [Fact]
    public void Run_TypesWhoseIdsAreKeywords_DisablesThoseIds()
    {
        var source =
            Source
            + """

                namespace MyApp
                {
                    [System.Diagnostics.CodeAnalysis.Experimental("if")]
                    public readonly struct TrialId;

                    [System.Obsolete("Use another.", DiagnosticId = "class")]
                    public sealed class OldName;
                }
                """;

        var run = Run(
            source,
            [Users, Sidecars.Of(Users, Entry(Users, "GetUser", [], [Column("id"), Column("name", Text)]))],
            new Dictionary<string, string?> { ["SqlSourceTypeOverrides"] = "int4=MyApp.TrialId text=MyApp.OldName" }
        );

        AssertClean(run);
        run.Sources["App.GetUserDto-Model.g.cs"]
            .ShouldStartWith(
                "// <auto-generated/>\n#nullable enable\n#pragma warning disable class, if "
                    + "// A mapped type is obsolete or experimental.\n\n"
            );
    }

    // A use of a type marked [Obsolete] as an error is CS0619, which no pragma disables, so the type is refused.
    [Fact]
    public void Run_TypeObsoleteAsAnError_IsSqlsrc252AndHasNoModel()
    {
        var source =
            Source
            + """

                namespace MyApp
                {
                    [System.Obsolete("Gone.", true)]
                    public sealed class GoneName;
                }
                """;

        var run = Run(
            source,
            [Users, Sidecars.Of(Users, Entry(Users, "GetUser", [], [Column("name", Text)]))],
            new Dictionary<string, string?> { ["SqlSourceTypeOverrides"] = "text=MyApp.GoneName" }
        );

        run.Diagnostics.ShouldHaveSingleItem()
            .ShouldStartWith(
                "SQLSRC252 /app/Repo/Users.sql(1,10)-(1,17): The type override maps 'text' to 'MyApp.GoneName' for "
                    + "column 'name', in the property SqlSourceTypeOverrides, and no property can have that type."
            );
        run.CompilationErrors.ShouldBeEmpty();
        run.GeneratedCodeWarnings.ShouldBeEmpty();
        ModelFiles(run).ShouldBeEmpty();
    }

    // An attribute of the name with arguments of another shape, here arrays, is read as giving no id and as not an
    // error, and never throws.
    public static TheoryData<string> MalformedAttributes =>
        [
            """
                namespace System.Diagnostics.CodeAnalysis
                {
                    [System.AttributeUsage(System.AttributeTargets.All)]
                    internal sealed class ExperimentalAttribute : System.Attribute
                    {
                        public ExperimentalAttribute(string[] diagnosticIds) { }
                    }
                }

                namespace MyApp
                {
                    [System.Diagnostics.CodeAnalysis.Experimental(new[] { "TRIAL001" })]
                    public sealed class OddName;
                }
                """,
            """
                namespace System
                {
                    [AttributeUsage(AttributeTargets.All)]
                    public sealed class ObsoleteAttribute : Attribute
                    {
                        public string[] DiagnosticId { get; set; }
                    }
                }

                namespace MyApp
                {
                    [System.Obsolete(DiagnosticId = new[] { "MYAPP001" })]
                    public sealed class OddName;
                }
                """,
            """
                namespace System
                {
                    [AttributeUsage(AttributeTargets.All)]
                    public sealed class ObsoleteAttribute : Attribute
                    {
                        public ObsoleteAttribute(string message, bool[] error) { }
                    }
                }

                namespace MyApp
                {
                    [System.Obsolete("Old.", new[] { true })]
                    public sealed class OddName;
                }
                """,
        ];

    [Theory]
    [MemberData(nameof(MalformedAttributes))]
    public void Run_TypeWithAMalformedAttribute_Compiles(string declarations)
    {
        var run = Run(
            Source + "\n\n" + declarations,
            [Users, Sidecars.Of(Users, Entry(Users, "GetUser", [], [Column("name", Text)]))],
            new Dictionary<string, string?> { ["SqlSourceTypeOverrides"] = "text=MyApp.OddName" }
        );

        AssertClean(run);
        ModelFiles(run).ShouldBe(["App.GetUserDto-Model.g.cs"]);
    }

    private static void AssertClean(GeneratorRun run)
    {
        run.Diagnostics.ShouldBeEmpty();
        run.CompilationErrors.ShouldBeEmpty();
        run.GeneratedCodeWarnings.ShouldBeEmpty();
    }
}
