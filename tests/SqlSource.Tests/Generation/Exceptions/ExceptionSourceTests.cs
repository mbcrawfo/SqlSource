using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Shouldly;
using SqlSource.Generation.Exceptions;
using Xunit;

namespace SqlSource.Tests.Generation.Exceptions;

// The exceptions' file goes into every project that references the package, unless a reference gives it the
// exceptions, so a project on an older language gets it too.
public sealed class ExceptionSourceTests
{
    [Theory]
    [InlineData(false, Accessibility.Internal)]
    [InlineData(true, Accessibility.Public)]
    public void TextFor_CompiledAsCSharp73_DeclaresBothExceptions(bool isPublic, Accessibility accessibility)
    {
        var compilation = CompileText(isPublic);

        compilation.GetDiagnostics(TestContext.Current.CancellationToken).ShouldBeEmpty();
        foreach (
            var name in new[]
            {
                ExceptionSource.UnexpectedRowCountMetadataName,
                ExceptionSource.TransactionRolledBackMetadataName,
            }
        )
        {
            var exception = compilation.GetTypeByMetadataName(name).ShouldNotBeNull();
            exception.BaseType!.ToDisplayString().ShouldBe("System.InvalidOperationException");
            exception.DeclaredAccessibility.ShouldBe(accessibility);
            exception.IsSealed.ShouldBeTrue();
        }
    }

    // The file is written whole: its two texts differ by the accessibility of the classes alone.
    [Fact]
    public void TextFor_PublicAndInternal_DifferOnlyInTheClassesAccessibility()
    {
        ExceptionSource
            .TextFor(isPublic: true)
            .Replace("public sealed class", "internal sealed class", StringComparison.Ordinal)
            .ShouldBe(ExceptionSource.TextFor(isPublic: false));
        ExceptionSource.TextFor(isPublic: false).ShouldStartWith("// <auto-generated/>\n");
        ExceptionSource.TextFor(isPublic: false).ShouldNotContain("#pragma");
        ExceptionSource.TextFor(isPublic: true).ShouldBeSameAs(ExceptionSource.TextFor(isPublic: true));
    }

    [Theory]
    [InlineData(false, "The query 'GetUser' returned no rows.")]
    [InlineData(true, "The query 'GetUser' returned more than one row.")]
    public void UnexpectedRowCountException_Created_NamesTheQueryAndWhatWentWrong(bool moreThanOne, string message)
    {
        var type = Load(ExceptionSource.UnexpectedRowCountMetadataName);

        var exception = (InvalidOperationException)Activator.CreateInstance(type, "GetUser", moreThanOne)!;

        exception.Message.ShouldBe(message);
        type.GetProperty("QueryName")!.GetValue(exception).ShouldBe("GetUser");
    }

    [Fact]
    public void TransactionRolledBackException_Created_NamesTheQueryAndKeepsTheInnerException()
    {
        var type = Load(ExceptionSource.TransactionRolledBackMetadataName);
        var inner = new FormatException("The value is not a number.");

        var exception = (InvalidOperationException)Activator.CreateInstance(type, "GetUser", inner)!;

        exception.Message.ShouldBe(
            "The transaction was rolled back by an error that the query 'GetUser' raised after the inner exception "
                + "was thrown."
        );
        exception.InnerException.ShouldBeSameAs(inner);
        type.GetProperty("QueryName")!.GetValue(exception).ShouldBe("GetUser");
    }

    // The public text, compiled and loaded, so that Activator reaches the constructors.
    private static Type Load(string metadataName)
    {
        using var image = new MemoryStream();
        CompileText(isPublic: true)
            .Emit(image, cancellationToken: TestContext.Current.CancellationToken)
            .Success.ShouldBeTrue();
        return Assembly.Load(image.ToArray()).GetType(metadataName).ShouldNotBeNull();
    }

    private static IEnumerable<MetadataReference> References() =>
        ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Select(path => (MetadataReference)MetadataReference.CreateFromFile(path));

    private static CSharpCompilation CompileText(bool isPublic) =>
        CSharpCompilation.Create(
            "ExceptionText",
            [
                CSharpSyntaxTree.ParseText(
                    ExceptionSource.TextFor(isPublic),
                    new CSharpParseOptions(LanguageVersion.CSharp7_3, DocumentationMode.Diagnose)
                ),
            ],
            References(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
        );
}
