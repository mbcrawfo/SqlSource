        // The system procedure sys.sp_executesql.
        "sp_executesql",
        // The table msdb.dbo.sysjobs.
        "sysjobs",
    ];

    /// <summary>The user's words, folded as <see cref="SqlServerRenaming.Fold" /> folds.</summary>
    public static IReadOnlySet<string> Words { get; } = FoldedSet(Spelled);

    /// <summary>The names of system objects that the corpora use, folded.</summary>
    public static IReadOnlySet<string> EngineRowNames { get; } = FoldedSet(EngineRowSpelled);

    /// <summary>The user's words in their natural spelling, sorted.</summary>
    public static IReadOnlyList<string> Spellings => Spelled;

    private static FrozenSet<string> FoldedSet(IEnumerable<string> spellings) =>
        spellings
            .Select(word => SqlServerRenaming.Instance.Fold(word, quoted: false))
            .ToFrozenSet(StringComparer.Ordinal);
