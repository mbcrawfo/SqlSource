-- The schema of the database "realistic", which the corpus of realistic queries in tests/DatabaseTests/Postgres is
-- described and executed against.  PostgresContainer applies it, then seed.sql, once for the run.  It stands apart
-- from the fixture schema: a change here moves no capture of the fixtures.  A column is added only when a case
-- needs it.

CREATE SCHEMA billing;

CREATE DOMAIN email_t AS text CHECK (VALUE LIKE '%@%');

-- A domain with a NOT NULL of its own.
CREATE DOMAIN positive_amount AS numeric(12, 2) NOT NULL CHECK (VALUE > 0);

CREATE TYPE account_status AS ENUM ('active', 'suspended', 'closed');

CREATE TABLE accounts (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    email email_t,
    status account_status NOT NULL DEFAULT 'active',
    tags text[] NOT NULL DEFAULT '{}',
    settings jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    closed_at timestamptz
);

-- The tree, for recursive queries and self-joins.
CREATE TABLE categories (
    id integer PRIMARY KEY,
    parent_id integer REFERENCES categories (id),
    name text NOT NULL,
    slug text NOT NULL UNIQUE
);

CREATE TABLE products (
    id integer PRIMARY KEY,
    category_id integer REFERENCES categories (id),
    sku text NOT NULL UNIQUE,
    name text NOT NULL,
    price numeric(12, 2) NOT NULL,
    discontinued_on date
);

CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer NOT NULL REFERENCES accounts (id),
    placed_at timestamptz NOT NULL,
    shipped_at timestamptz,
    note text,
    coupon text
);

CREATE TABLE order_lines (
    order_id bigint NOT NULL REFERENCES orders (id),
    line_no integer NOT NULL,
    product_id integer NOT NULL REFERENCES products (id),
    quantity integer NOT NULL,
    unit_price numeric(12, 2) NOT NULL,
    PRIMARY KEY (order_id, line_no)
);

CREATE TABLE billing.invoices (
    id integer PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders (id),
    amount positive_amount,
    issued_on date NOT NULL,
    paid_on date
);

-- A partition on each side of 2025-01-01, for a partitioned table on either side of an outer join.
CREATE TABLE events (
    id bigint NOT NULL,
    account_id integer NOT NULL,
    at timestamptz NOT NULL,
    kind text NOT NULL,
    payload jsonb
) PARTITION BY RANGE (at);

CREATE TABLE events_2024 PARTITION OF events FOR VALUES FROM (MINVALUE) TO ('2025-01-01');

CREATE TABLE events_2025 PARTITION OF events FOR VALUES FROM ('2025-01-01') TO (MAXVALUE);

CREATE TABLE reservations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer NOT NULL REFERENCES accounts (id),
    during tstzrange NOT NULL
);

-- A view over an outer join: order_id and placed_at can be NULL in it.
CREATE VIEW account_orders AS
SELECT a.id AS account_id, a.name, o.id AS order_id, o.placed_at
FROM accounts a
LEFT JOIN orders o ON o.account_id = a.id;
